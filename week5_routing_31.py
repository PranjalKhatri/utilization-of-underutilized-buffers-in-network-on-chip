import subprocess
import os

# Configuration
routing_algos = [0, 1, 3]  # 0: Table, 1: XY, 3: Odd-Even
traffic_patterns = ["bit_complement", "tornado"]

# Network dimensions
num_nodes = 16
mesh_rows = 4
injection_rate = 0.1
sim_cycles = 100000000

# File names
temp_file = "packet_paths.txt"
master_file = "all_packet_paths_summary.txt"

# Clear the master file if it exists from a previous run
with open(master_file, "w") as f:
    f.write("=== Gem5 Routing Algorithm Evaluation ===\n\n")

for pattern in traffic_patterns:
    for algo in routing_algos:
        print(f"Running: Pattern = {pattern}, Routing Algorithm = {algo}...")
        
        # Construct the gem5 command
        cmd = [
            "./build/NULL/gem5.opt",
            "configs/example/garnet_synth_traffic.py",
            "--network=garnet",
            f"--num-cpus={num_nodes}",
            f"--num-dirs={num_nodes}",
            "--topology=Mesh_XY",
            f"--mesh-rows={mesh_rows}",
            f"--routing-algorithm={algo}",
            f"--synthetic={pattern}",
            f"--injectionrate={injection_rate}",
            f"--sim-cycles={sim_cycles}"
        ]
        
        # Remove the temp file before running to ensure we don't read stale data
        if os.path.exists(temp_file):
            os.remove(temp_file)

        # Execute the command, redirecting all terminal output to NULL
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            
        # Read the file generated by the C++ code and append it to the master log
        if os.path.exists(temp_file):
            with open(temp_file, "r") as temp_f:
                output_data = temp_f.read()
                
            with open(master_file, "a") as master_f:
                master_f.write(f"--------------------------------------------------\n")
                master_f.write(f"TRAFFIC: {pattern.upper()} | ALGO: {algo}\n")
                master_f.write(f"--------------------------------------------------\n")
                master_f.write(output_data)
                master_f.write("\n\n")
        else:
            print(f"Warning: {temp_file} was not generated for {pattern} (Algo {algo})")

print(f"All simulations complete! Check {master_file} for the appended results.")